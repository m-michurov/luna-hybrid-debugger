import shutil
from pathlib import Path

import click

from adapt_file_paths import REQUIRED_FILE_PATHS
from path_utility import resolve_relative_to
from instrument_cpp import run as instrument_cpp
from instrument_luna import run as instrument_luna


@click.command()
@click.argument(
    'project-path',
    nargs=1,
    type=click.Path(
        dir_okay=True,
        file_okay=False,
        resolve_path=True,
        path_type=Path,
    )
)
@click.option(
    '--build-dir',
    required=False,
    show_default=True,
    default=Path('build'),
    help='Directory for build files.',
    type=click.Path(
        file_okay=False,
        resolve_path=False,
        path_type=Path,
    )
)
@click.option(
    '--output-dir',
    required=False,
    show_default=True,
    default=Path('instrumented'),
    help='Directory for program output.',
    type=click.Path(
        file_okay=False,
        resolve_path=False,
        path_type=Path,
    )
)
@click.option(
    '--atomic-ddg',
    required=False,
    show_default=True,
    default=Path('atomic_ddg.json'),
    help='A JSON file containing information about data dependencies between atomic CF arguments.',
    type=click.Path(
        dir_okay=False,
        resolve_path=False,
        path_type=Path,
    )
)
@click.option(
    '--found-errors',
    required=False,
    show_default=True,
    default=Path('.adapt', 'reporter', 'found_errors.json'),
    help='Use found_errors.json file generated by other ADAPT modules to insert only necessary checks.',
    type=click.Path(
        file_okay=True,
        resolve_path=False,
        path_type=Path,
    )
)
def main(
        project_path: Path,
        output_dir: Path,
        build_dir: Path,
        found_errors: Path,
        atomic_ddg: Path | None = None
) -> None:
    assert_generator_home = Path(__file__).parent
    luna_after_ja_path = resolve_relative_to(Path('luna_after_ja', 'luna'), assert_generator_home)

    output_dir = resolve_relative_to(output_dir, project_path)
    build_dir = resolve_relative_to(build_dir, output_dir)
    found_errors = resolve_relative_to(found_errors, project_path)
    atomic_ddg = resolve_relative_to(atomic_ddg, project_path)

    if output_dir.exists():
        shutil.rmtree(output_dir, ignore_errors=False)
    output_dir.mkdir(parents=True, exist_ok=False)

    for path in REQUIRED_FILE_PATHS:
        shutil.copyfile(path, output_dir / path.name)

    cpp_paths = [it.resolve() for it in project_path.iterdir() if it.suffix in ['.C', '.cpp', '.cc']]
    for cpp_path in cpp_paths:
        print(f'Instrumenting "{cpp_path}"...')
        instrument_cpp(
            cpp_path=cpp_path,
            output_dir=output_dir,
            atomic_ddg=atomic_ddg,
            standalone=False,
        )

    print(f'Instrumenting LuNA code in "{project_path}"...')
    instrument_luna(
        project_path=project_path,
        build_dir=build_dir,
        output_dir=output_dir,
        found_errors=found_errors,
        standalone=False,
    )

    print('Run modified program with:')
    print(f'cd {output_dir} ;', end=' ')
    print(f'rm -f .adapt_error_*.dat ;', end=' ')
    print(
        f'{luna_after_ja_path}',
        '-g',
        f'--build-dir={str(build_dir)}',
        '--no-cleanup',
        *(str(it.resolve()) for it in output_dir.iterdir() if it.suffix == '.fa'),
        ';',
        sep=' ',
        end=' '
    )
    print(f'cd -')


if __name__ == '__main__':
    main()
