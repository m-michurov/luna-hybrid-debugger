import shutil
import subprocess
import sys
from pathlib import Path
from typing import Final

import click

from file_paths import HYBRID_DEBUGGER_HOME, PYTHON_EXECUTABLE_PATH, FORMAT_ERRORS_PATH, REQUIRED_C_FILE_PATHS
from instrument_cpp import instrument_cpp
from instrument_luna import instrument_luna
from path_utility import resolve_relative_to

OPTION_OUTPUT_DIR: Final[str] = '--output-dir'
ERRORS_FILE_PATH_DEFAULT: Final[Path] = Path('errors.json')


@click.command(
    context_settings=dict(
        ignore_unknown_options=True,
    )
)
@click.argument(
    'fa-path',
    nargs=1,
    type=click.Path(
        dir_okay=False,
        file_okay=True,
        resolve_path=False,
        path_type=Path,
    )
)
@click.argument(
    'fa-args',
    nargs=-1,
    type=click.UNPROCESSED
)
@click.option(
    OPTION_OUTPUT_DIR,
    required=False,
    show_default=True,
    default=Path('.hybrid-debugger'),
    help='Directory for program output.',
    type=click.Path(
        file_okay=False,
        resolve_path=False,
        path_type=Path,
    )
)
@click.option(
    '--atomic-ddg',
    required=False,
    show_default=True,
    default=Path('atomic_ddg.json'),
    help='A JSON file containing information about data dependencies between atomic CF arguments.',
    type=click.Path(
        dir_okay=False,
        resolve_path=False,
        path_type=Path,
    )
)
@click.option(
    '--found-errors',
    required=False,
    show_default=True,
    default=Path('.adapt', 'reporter', 'found_errors.json'),
    help='Use errors file generated by other ADAPT modules to insert only necessary checks.',
    type=click.Path(
        file_okay=True,
        resolve_path=False,
        path_type=Path,
    )
)
@click.option(
    '--instrument-only',
    is_flag=True,
    help='Generate runtime checks and print the command to run the modified program.'
)
@click.option(
    '--no-cleanup',
    is_flag=True,
    help='Keep instrumented files.'
)
@click.option(
    '--errors-file',
    required=False,
    show_default=True,
    default=None,
    help=f'Append errors list to existing file or create a new errors file. '
         f'If not absolute, resolved relative to {OPTION_OUTPUT_DIR}.',
    type=click.Path(
        dir_okay=False,
        resolve_path=False,
        path_type=Path,
    )
)
def main(
        fa_path: Path,
        fa_args: list[str],
        output_dir: Path,
        found_errors: Path,
        atomic_ddg: Path | None = None,
        instrument_only: bool = False,
        no_cleanup: bool = False,
        errors_file: Path | None = None,
) -> int:
    luna_after_ja_path = resolve_relative_to(Path('luna_after_ja', 'luna'), HYBRID_DEBUGGER_HOME).resolve()

    project_path = fa_path.parent

    output_dir = resolve_relative_to(output_dir, root=project_path)
    if output_dir.resolve() == project_path.resolve():
        print(f'ERROR: Output directory "{output_dir}" is the same as project directory.')
        return 1

    build_dir = output_dir / 'build'
    found_errors = resolve_relative_to(found_errors, root=project_path)
    atomic_ddg = resolve_relative_to(atomic_ddg, root=project_path)

    if output_dir.exists():
        shutil.rmtree(output_dir, ignore_errors=False)
    output_dir.mkdir(parents=True, exist_ok=False)

    for path in REQUIRED_C_FILE_PATHS:
        shutil.copyfile(path, output_dir / path.name)

    for path in project_path.iterdir():
        if path.resolve() == output_dir.resolve():
            continue

        shutil.copy(path, output_dir / path.name)

    cpp_paths = [it for it in project_path.iterdir() if it.suffix in ['.C', '.cpp', '.cc']]
    for cpp_path in cpp_paths:
        print(f'Instrumenting "{cpp_path}"...')
        instrument_cpp(
            cpp_path=cpp_path,
            output_dir=output_dir,
            data_dependencies_file_path=atomic_ddg,
        )

    print(f'Instrumenting LuNA code in "{project_path}"...')
    instrument_luna(
        fa_path=fa_path,
        fa_args=fa_args,
        build_dir=build_dir,
        output_dir=output_dir,
        found_errors=found_errors,
    )

    instrumented_fa_path = output_dir / fa_path.name

    if errors_file is None:
        errors_file = output_dir / 'errors.json'

    if errors_file.parent == output_dir:
        no_cleanup = True

    run_command = ' '.join([
        f'cd {output_dir.resolve()}',
        f'&& rm -f adapt_error_*.dat',
        f'&& {luna_after_ja_path} -g --build-dir={str(build_dir.resolve())} --no-cleanup',
        str(instrumented_fa_path.resolve()),
        *fa_args,
        f'; cd $OLDPWD',
        f'&& {PYTHON_EXECUTABLE_PATH} {FORMAT_ERRORS_PATH} --errors-file {str(errors_file.resolve())} {str(output_dir.resolve())}',
        f'&& rm -rf {output_dir.resolve()}' if not no_cleanup else ''
    ])

    if instrument_only:
        print('Run modified program with:')
        print(run_command)
        return 0

    try:
        print('Running modified program:')

        p = subprocess.run(
            args=run_command,
            # cwd=project_path,
            capture_output=True,
            check=True,
            shell=True,
        )
        print(p.stdout.decode())
        print(p.stderr.decode())
    except subprocess.CalledProcessError as e:
        print(e.stderr.decode(), file=sys.stderr)
        return 1

    return 0


if __name__ == '__main__':
    sys.exit(main())
